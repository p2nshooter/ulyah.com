const DAYS = ['げつようび', 'かようび', 'すいようび', 'もくようび', 'きんようび', 'どようび', 'にちようび'] as const;
const THINGS = [['ぎゅうにゅう', 'たまご', 'パン', 'りんご', 'バナナ', 'ジュース'], ['ノート', 'えんぴつ', 'けしゴム', 'ふうとう', 'きって', 'ボールペン']] as const;
const PRICES = [100, 150, 200, 250, 300, 350, 400, 500, 600, 800] as const;
const yen = (n: number) => `${n}えん`;

export function n5Point(r: R, i: number): MItem {
  const kind = i % 3;
  if (kind === 0) {
    const a = Math.floor(r() * 9), b = Math.min(11, a + 1 + Math.floor(r() * 2));
    return it('おとこの ひとは なんじに えきへ いきますか。', [H_NUM[a]!, H_NUM[b]!, `${H_NUM[a]}はん`, `${H_NUM[b]}はん`], 2,
      `Awalnya ${H_NUM[a]}, lalu diubah menjadi ${H_NUM[a]}はん (setengah).`, { audio: [N('おとこの ひとと おんなの ひとが はなして います。おとこの ひとは なんじに えきへ いきますか。'), F('あした なんじに えきへ いきますか。'), M(`${HOURS[a]}に いきます。`), F(`でんしゃは ${HOURS[b]}ですよ。${HOURS[a]}は ちょっと はやいですね。`), M(`そうですね。じゃあ、${HOURS[a]}はんに いきます。`), N('おとこの ひとは なんじに えきへ いきますか。')] });
  }
  if (kind === 1) {
    const d = Math.floor(r() * 5), e = d + 1 + Math.floor(r() * 2);
    return it('おんなの ひとは なんようびに びょういんへ いきますか。', [DAYS[d]!, DAYS[e]!, DAYS[(e + 1) % 7]!, DAYS[(d + 6) % 7]!], 1,
      `${DAYS[d]} tutup, jadi pergi ${DAYS[e]}.`, { audio: [N('おんなの ひとと おとこの ひとが はなして います。おんなの ひとは なんようびに びょういんへ いきますか。'), M('びょういんへは いつ いきますか。'), F(`${DAYS[d]}に いきたいです。`), M(`あ、あの びょういんは ${DAYS[d]}は やすみですよ。`), F(`そうですか。じゃあ、${DAYS[e]}に いきます。`), N('おんなの ひとは なんようびに びょういんへ いきますか。')] });
  }
  const p = Math.floor(r() * 6), q = Math.floor(r() * 3) + 2;
  const price = PRICES[p]!, total = price * q;
  const opts = [yen(price), yen(total), yen(price * (q + 1)), yen(total + 50)];
  return it('おとこの ひとは ぜんぶで いくら はらいますか。', opts, 1, `${yen(price)} × ${q} = ${yen(total)}.`, { audio: [N('みせで おとこの ひとと みせの ひとが はなして います。おとこの ひとは ぜんぶで いくら はらいますか。'), M('すみません、この りんごは いくらですか。'), F(`ひとつ ${price}えんです。`), M(`じゃあ、${q}つ ください。`), F(`はい、ぜんぶで ${total}えんです。`), N('おとこの ひとは ぜんぶで いくら はらいますか。')] });
}

export function n5Kadai(r: R, i: number): MItem {
  const set = THINGS[i % 2]!;
  const idx = [0, 1, 2, 3, 4, 5].sort(() => r() - 0.5);
  const [a, b, c, d] = idx.map((k) => set[k]!);
  const where = i % 2 ? 'ぶんぼうぐや' : 'スーパー';
  return it(`おんなの ひとは ${where}で なにを かいますか。`, [`${a}と ${b}`, `${a}と ${c}`, `${b}と ${c}`, `${c}と ${d}`], 1,
    `${b} masih ada di rumah, jadi yang dibeli ${a} dan ${c}.`, { audio: [N(`おとこの ひとと おんなの ひとが はなして います。おんなの ひとは ${where}で なにを かいますか。`), F(`これから ${where}へ いきます。${a}と ${b}を かいます。`), M(`${b}は まだ うちに ありますよ。`), F(`そうですか。じゃあ、${b}は かいません。${c}を かいます。`), M('おねがいします。'), N(`おんなの ひとは ${where}で なにを かいますか。`)] });
}
