export type Key = keyof typeof D;
export const KEYS = Object.keys(D) as Key[];

/** Teks antarmuka dalam bahasa L; {nama} diganti dari vars. */
export function t(L: Lang, key: Key, vars?: Record<string, string | number>): string {
  let s: string = D[key][IX[L]];
  if (vars) for (const [k, v] of Object.entries(vars)) s = s.split(`{${k}}`).join(String(v));
  return s;
}

/** Kamus untuk skrip peramban (hanya kunci js.*, common.* yang dipakai, plus lesson.* tombol). */
export function clientDict(L: Lang): Record<string, string> {
  const out: Record<string, string> = {};
  for (const k of KEYS) if (k.startsWith('js.') || k === 'common.copied' || k === 'common.grading' || k === 'common.offline' || k === 'common.gradeFail' || k === 'common.play' || k === 'common.slow' || k === 'common.listen' || k === 'lesson.hideTr' || k === 'lesson.showTr' || k === 'lesson.focus' || k === 'lesson.focusOff' || k === 'lesson.quizSubmit' || k === 'practice.submit' || k === 'common.perLang' || k === 'common.threeLangs' || k === 'practice.guest.login') out[k] = D[k][IX[L]];
  return out;
}

export function fmtNum(L: Lang, n: number, dec = 0): string {
  return n.toLocaleString(UI_LOCALE[L], { minimumFractionDigits: dec, maximumFractionDigits: dec });
}

/** Rupiah tanpa desimal: Rp500.000 */
export const rp = (n: number): string => `Rp${Math.round(n).toLocaleString('id-ID')}`;

export function fmtDate(L: Lang, ms: number, withTime = false): string {
  const d = new Date(ms);
  const opts: Intl.DateTimeFormatOptions = { timeZone: 'Asia/Jakarta', day: 'numeric', month: 'long', year: 'numeric' };
  if (withTime) Object.assign(opts, { hour: '2-digit', minute: '2-digit' });
  const s = d.toLocaleString(UI_LOCALE[L], opts);
  return withTime ? `${s} WIB` : s;
}

/** Tanggal WIB "YYYY-MM-DD" untuk kunci log harian. */
export const wibDate = (ms = Date.now()): string => new Date(ms + 7 * 3600_000).toISOString().slice(0, 10);
